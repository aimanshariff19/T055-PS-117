import { getReports } from "./api.js";
import {
  emptyState, errorState, escapeHtml, formatNumber, icon, loadingState, note, pageHeader,
} from "./dashboard.js";

export async function renderPage(root) {
  root.innerHTML = loadingState("Checking available report files…");
  let payload;
  try {
    payload = await getReports();
  } catch (error) {
    root.innerHTML = pageHeader("Data exports", "Reports", "Download CSV reports generated by the Java engine.") + errorState(error);
    root.querySelector('[data-action="retry"]')?.addEventListener("click", () => renderPage(root));
    return;
  }
  const reports = payload.reports || [];
  root.innerHTML = `${pageHeader("Data exports", "Reports", "Only files that exist in the configured engine output directory are listed.")}
    ${note(payload.processed ? "Showing report files from the latest API-triggered engine run." : "Showing report files already present in the configured output directory. Reports are not synthesized by the dashboard.", payload.processed ? "" : "warning")}
    <section class="panel table-panel"><div class="panel-header"><div><h2 class="panel-title">Available CSV reports</h2><div class="panel-subtitle">${reports.length} files available for download</div></div></div>
    ${reports.length ? `<div class="table-wrap"><table><thead><tr><th>Report</th><th>File</th><th>Size</th><th>Data note</th><th>Download</th></tr></thead><tbody>${reports.map((report) => `<tr>
      <td class="primary-cell">${escapeHtml(report.name)}</td><td class="mono">${escapeHtml(report.fileName)}</td>
      <td>${formatNumber(report.sizeBytes)} bytes</td><td>${escapeHtml(report.note)}</td>
      <td><a class="row-action" href="${escapeHtml(report.downloadUrl)}" download>${icon("download")}CSV</a></td>
    </tr>`).join("")}</tbody></table></div>` : emptyState("No reports available", "Run Java processing to generate CSV reports. The dashboard will not fabricate report data.", "chart")}</section>`;
}
